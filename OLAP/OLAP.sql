CREATE TABLE dim_servicios(
    id_servicio NUMBER,
    codigo_estandar VARCHAR2(50),
    descripcion VARCHAR2(100),
    tipo_servicio VARCHAR2(100),
    especialidad VARCHAR2(100),
    precio_unitario NUMBER(10, 2)
);

