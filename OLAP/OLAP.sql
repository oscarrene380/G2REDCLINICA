CREATE TABLE dim_seguros(
    id_seguro NUMBER,
    plan VARCHAR2(50),
    aseguradora VARCHAR2(100)
);

-- INSERT DE DATOS
SELECT 
    S.ID_SEGURO,
    S.PLAN,
    A.NOMBRE AS ASEGURADORA
FROM TRX_SEGUROS S INNER JOIN ASEGURADORAS A
ON S.ID_ASEGURADORA=A.ID_ASEGURADORA;


