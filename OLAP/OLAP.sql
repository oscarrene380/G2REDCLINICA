CREATE TABLE dim_paciente(
    id_paciente NUMBER NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    sexo CHAR(1),
    fecha_nacimiento DATE NOT NULL,
    edad INT NOT NULL,
    telefono VARCHAR2(15),
    email VARCHAR2(2),
    direccion VARCHAR2(200),
    departamento  VARCHAR2(50),
    municipio  VARCHAR2(50),
    distrito  VARCHAR2(50)
);

-- INSERT DE DATOS
SELECT 
    P.ID_PACIENTE, P.NOMBRE, P.SEXO, P.FECHA_NACIMIENTO, P.EDAD, 
    P.TELEFONO, P.EMAIL, P.DIRECCION,
    D.NOMBRE AS DEPARTAMENTO, M.NOMBRE AS MUNICIPIO, D.NOMBRE AS DISTRITO
FROM TRX_PACIENTES P INNER JOIN DISTRITOS D
ON P.ID_DISTRITO=D.ID_DISTRITO INNER JOIN MUNICIPIOS M
ON D.ID_MUNICIPIO=M.ID_MUNICIPIO INNER JOIN DEPARTAMENTOS DP
ON M.ID_DEPARTAMENTO=DP.ID_DEPARTAMENTO;


CREATE TABLE dim_medico (
    id_medico NUMBER,
    nombre VARCHAR2(100),
    numero_registro VARCHAR2,
    direccion VARCHAR2(200),
    telefono VARCHAR2(15),
    email VARCHAR2(100),
    especialidad VARCHAR2(100)
);

-- INSERT DE DATOS
SELECT 
    M.ID_MEDICO,
    M.NOMBRE, M.NUMERO_REGISTRO, M.DIRECCION, M.TELEFONO, M.EMAIL, E.NOMBRE AS ESPECIALIDAD
FROM TRX_MEDICOS M INNER JOIN TRX_MEDICO_ESPECIALIDADES ME
ON M.ID_MEDICO=ME.ID_MEDICO INNER JOIN TRX_ESPECIALIDADES E
ON ME.ID_ESPECIALIDAD=E.ID_ESPECIALIDAD;

CREATE TABLE dim_unidades (
    id_unidad NUMBER,
    nombre VARCHAR2(100),
    direccion VARCHAR2(200),
    distrito VARCHAR2(50),
    tipo VARCHAR2(50)
);

-- INSERT DE DATOS
SELECT 
    ID_UNIDAD,
    U.NOMBRE, 
    DIRECCION, 
    D.NOMBRE AS DISTRITO,
    U.TIPO
FROM TRX_UNIDADES U INNER JOIN DISTRITOS D
ON U.ID_DISTRITO=D.ID_DISTRITO;

