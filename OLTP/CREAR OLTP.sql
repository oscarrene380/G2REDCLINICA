    updated_at      TIMESTAMP,
    CONSTRAINT fk_atencion_seguro   FOREIGN KEY (id_seguro)   REFERENCES trx_seguros(id_seguro),
    CONSTRAINT fk_detalle_atencion FOREIGN KEY (id_atencion) REFERENCES trx_atenciones(id_atencion),
    CONSTRAINT fk_detalle_servicio FOREIGN KEY (id_servicio) REFERENCES trx_servicios(id_servicio),
    CONSTRAINT fk_detalle_medico   FOREIGN KEY (id_medico)   REFERENCES trx_medicos(id_medico)
