-- DETALLE DE SERVICIOS PRESTADOS EN CADA ATENCION
CREATE TABLE trx_detalle (
    id_detalle      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atencion     NUMBER NOT NULL,
    id_servicio     NUMBER NOT NULL,
    id_seguro       NUMBER, -- puede ser null si el paciente no tiene seguro
    id_medico       NUMBER NOT NULL,
    cantidad        NUMBER(5) DEFAULT 1,
    precio_unitario NUMBER(10,2),
    cobertura       NUMBER(10,2), -- cubierto por el seguro (validar si el paciente hace uso del seguro (tabla atenciones uso_seguro))
    --deducible       NUMBER(10,2), -- monto a cargo del paciente
